#!/usr/bin/env bash
# Выкладка браузерного демо игры в его GitHub Pages-репозиторий.
#
#   tools/publish_demo.sh <zip-или-папка-сборки> [репозиторий]
#   tools/publish_demo.sh ../tank_1990_big_map/html-demo/build/dist/tank1990-site-demo-1.7.1.zip
#
# Репозиторий по умолчанию — petrovbit/tank-1990-demo. Он публичный, Pages
# раздаёт ветку main из корня, и так как у организации есть сайт с CNAME
# petrovbit.dev, демо открывается на том же домене: petrovbit.dev/tank-1990-demo/.
# Тот же origin, что у сайта, — поэтому окно DemoHost (v2/demo.jsx) встраивает
# его iframe'ом без CORS и принимает postMessage.
#
# В репозиторий кладётся только собранная игра — исходники Java остаются в
# приватном репозитории игры. Каждая выкладка — один коммит, содержимое
# заменяется целиком, так что удалённые из сборки файлы исчезают и тут.
set -euo pipefail

SRC="${1:?укажи zip или папку сборки демо}"
REPO="${2:-petrovbit/tank-1990-demo}"
WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT

if [[ -d "$SRC" ]]; then
  BUILD="$SRC"
else
  mkdir "$WORK/unzip"
  unzip -q "$SRC" -d "$WORK/unzip"
  BUILD="$WORK/unzip"
  # zip может содержать одну корневую папку — спускаемся в неё
  if [[ ! -f "$BUILD/index.html" ]] && [[ "$(ls "$BUILD" | wc -l)" == 1 ]]; then
    BUILD="$BUILD/$(ls "$BUILD")"
  fi
fi
[[ -f "$BUILD/index.html" ]] || { echo "в $SRC нет index.html" >&2; exit 1; }

git clone -q "git@github.com:$REPO.git" "$WORK/repo"
cd "$WORK/repo"
git rm -rq --ignore-unmatch . >/dev/null
cp -a "$BUILD"/. .
# Без .nojekyll Pages прогоняет сайт через Jekyll и прячет файлы с «_» в начале.
touch .nojekyll
cat > README.md <<'MD'
# Tank 1990 — browser demo

Build output of the Tank 1990: Big Map Battle browser demo (first stage only),
served at https://petrovbit.dev/tank-1990-demo/ and embedded on https://petrovbit.dev.
Generated by `tools/publish_demo.sh` in the website repository — do not edit by hand.
MD

git add -A
if git diff --cached --quiet; then
  echo "изменений нет, выкладывать нечего"
  exit 0
fi
git commit -q -m "Publish demo build $(basename "$SRC") ($(date -u +%Y-%m-%dT%H:%MZ))" ${PUBLISH_TRAILER:+-m "$PUBLISH_TRAILER"}
git push -q origin HEAD:main
echo "выложено: https://github.com/$REPO → https://petrovbit.dev/${REPO#*/}/"
